/* font5x7.h — a tiny bitmap font for status text, without any font library (given).
 *
 * font5x7_glyph(c) returns 7 rows of 5 bits (bit 4 = the leftmost pixel) for digits, letters
 * (lower case is drawn as upper case) and a few signs, or NULL for anything else. Draw a pixel
 * (a filled square of your scale) for every set bit; 6 * scale is a good distance between letters.
 * It does not depend on any toolkit: SDL, raylib, GTK or Qt can all draw it. */
#ifndef FONT5X7_H
#define FONT5X7_H

#include <stddef.h>

static inline const unsigned char *font5x7_glyph(char c) {
    static const struct { char c; unsigned char rows[7]; } g[] = {
        {'0',{14,17,19,21,25,17,14}}, {'1',{4,12,4,4,4,4,14}},      {'2',{14,17,1,2,4,8,31}},
        {'3',{31,2,4,2,1,17,14}},     {'4',{2,6,10,18,31,2,2}},     {'5',{31,16,30,1,1,17,14}},
        {'6',{6,8,16,30,17,17,14}},   {'7',{31,1,2,4,8,8,8}},       {'8',{14,17,17,14,17,17,14}},
        {'9',{14,17,17,15,1,2,12}},   {'A',{14,17,17,31,17,17,17}}, {'B',{30,17,17,30,17,17,30}},
        {'C',{14,17,16,16,16,17,14}}, {'D',{28,18,17,17,17,18,28}}, {'E',{31,16,16,30,16,16,31}},
        {'F',{31,16,16,30,16,16,16}}, {'G',{14,17,16,23,17,17,15}}, {'H',{17,17,17,31,17,17,17}},
        {'I',{14,4,4,4,4,4,14}},      {'J',{7,2,2,2,2,18,12}},      {'K',{17,18,20,24,20,18,17}},
        {'L',{16,16,16,16,16,16,31}}, {'M',{17,27,21,21,17,17,17}}, {'N',{17,17,25,21,19,17,17}},
        {'O',{14,17,17,17,17,17,14}}, {'P',{30,17,17,30,16,16,16}}, {'Q',{14,17,17,17,21,18,13}},
        {'R',{30,17,17,30,20,18,17}}, {'S',{15,16,16,14,1,1,30}},   {'T',{31,4,4,4,4,4,4}},
        {'U',{17,17,17,17,17,17,14}}, {'V',{17,17,17,17,17,10,4}},  {'W',{17,17,17,21,21,21,10}},
        {'X',{17,17,10,4,10,17,17}},  {'Y',{17,17,17,10,4,4,4}},    {'Z',{31,1,2,4,8,16,31}},
        {'/',{1,1,2,4,8,16,16}},      {':',{0,12,12,0,12,12,0}},    {'-',{0,0,0,31,0,0,0}},
        {'+',{0,4,4,31,4,4,0}},       {'.',{0,0,0,0,0,12,12}},      {'(',{2,4,8,8,8,4,2}},
        {')',{8,4,2,2,2,4,8}},        {'=',{0,0,31,0,31,0,0}},      {',',{0,0,0,0,12,4,8}},
        {'[',{14,8,8,8,8,8,14}},      {']',{14,2,2,2,2,2,14}},      {'%',{24,25,2,4,8,19,3}},
    };
    if (c >= 'a' && c <= 'z') {
        c = (char)(c - 'a' + 'A');
    }
    for (size_t i = 0; i < sizeof(g) / sizeof(g[0]); i++) {
        if (g[i].c == c) {
            return g[i].rows;
        }
    }
    return NULL;                                     /* a space, or a sign we do not have */
}

#endif
